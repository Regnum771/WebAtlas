import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Target } from '../targets';
import type { Tokens } from '../tokens';
import { emitTokensCss } from './tokensCss';

/**
 * The Keycloak login theme (K6). The hand-written sources live in src/keycloak/; this builds the theme
 * folder Keycloak loads, generated/keycloak/webatlas/login/, which infra/docker-compose.platform.yml
 * mounts at /opt/keycloak/themes/webatlas. Only login.css takes tokens (the --wa-* block is prepended);
 * the templates, messages and icon are copied as they are, under a "generated" banner where the format
 * allows a comment.
 */
const SRC = fileURLToPath(new URL('../keycloak/', import.meta.url));
const OUT = 'keycloak/webatlas/login/';

const source = (name: string) => readFileSync(`${SRC}${name}`, 'utf8').replace(/\r\n/g, '\n');

const NOTE = 'Generated by @webatlas/theme from src/keycloak/NAME. Do not edit; run npm run generate:theme.';
const ftlBanner = (name: string) => `<#-- ${NOTE.replace('NAME', name)} -->\n`;
const propsBanner = (name: string) => `# ${NOTE.replace('NAME', name)}\n`;

export function emitKeycloakCss(t: Tokens): string {
  return `${emitTokensCss(t)}\n${source('login.css')}`;
}

const copy = (name: string, banner: (n: string) => string = () => '') => () => banner(name) + source(name);

export const keycloakTargets: readonly Target[] = [
  { id: 'keycloak-theme-properties', path: `${OUT}theme.properties`, emit: copy('theme.properties', propsBanner) },
  { id: 'keycloak-template', path: `${OUT}template.ftl`, emit: copy('template.ftl', ftlBanner) },
  { id: 'keycloak-login', path: `${OUT}login.ftl`, emit: copy('login.ftl', ftlBanner) },
  { id: 'keycloak-messages-vi', path: `${OUT}messages/messages_vi.properties`, emit: copy('messages_vi.properties', propsBanner) },
  { id: 'keycloak-messages-en', path: `${OUT}messages/messages_en.properties`, emit: copy('messages_en.properties', propsBanner) },
  { id: 'keycloak-css', path: `${OUT}resources/css/login.css`, emit: emitKeycloakCss },
  { id: 'keycloak-favicon', path: `${OUT}resources/img/favicon.svg`, emit: copy('favicon.svg') },
];
